


async def test_hr_creates_employee_with_autogenerated_code_and_balances(
    client, auth, world, admin_db
):
    headers = await auth("hr_a")
    response = await client.post(
        "/employees",
        json={
            "first_name": "Nikhil",
            "last_name": "Bose",
            "email": "nikhil@alpha.example",
            "department_id": world["departments"]["prod_a"],
            "date_of_joining": "2026-04-01",
        },
        headers=headers,
    )
    assert response.status_code == 201, response.text
    body = response.json()
    assert body["employee_code"] == "EMP-0004"
    assert body["department_name"] == "Production"
    assert body["has_account"] is False
    assert body["temporary_password"] is None

    employee_id = body["id"]
    assert (
        await admin_db.fetchval(
            "SELECT count(*) FROM leave_balances WHERE employee_id = $1", employee_id
        )
        == 1
    )
    assert (
        await admin_db.fetchval(
            "SELECT tenant_id FROM employees WHERE id = $1", employee_id
        )
        == world["tenants"]["alpha"]
    )


async def test_hr_creates_employee_with_login_and_deactivation(client, auth, world):
    headers = await auth("hr_a")
    response = await client.post(
        "/employees",
        json={
            "first_name": "Tara",
            "last_name": "Joshi",
            "email": "tara@alpha.example",
            "create_account": True,
            "role": "employee",
            "password": "Tara@2026!",
        },
        headers=headers,
    )
    assert response.status_code == 201, response.text
    employee_id = response.json()["id"]
    assert response.json()["has_account"] is True

    login = await client.post(
        "/auth/login", json={"email": "tara@alpha.example", "password": "Tara@2026!"}
    )
    assert login.status_code == 200
    employee_headers = {"Authorization": f"Bearer {login.json()['access_token']}"}

    me = await client.get("/employees/me", headers=employee_headers)
    assert me.status_code == 200
    assert me.json()["full_name"] == "Tara Joshi"

    deactivated = await client.patch(
        f"/employees/{employee_id}", json={"is_active": False}, headers=headers
    )
    assert deactivated.status_code == 200
    assert deactivated.json()["is_active"] is False

    blocked = await client.post(
        "/auth/login", json={"email": "tara@alpha.example", "password": "Tara@2026!"}
    )
    assert blocked.status_code == 403


async def test_employee_search_and_filters(client, auth, world):
    headers = await auth("hr_a")
    search = await client.get("/employees?q=esha", headers=headers)
    assert search.status_code == 200
    assert search.json()["total"] == 1
    assert search.json()["items"][0]["first_name"] == "Esha"

    by_department = await client.get(
        f"/employees?department_id={world['departments']['prod_a']}", headers=headers
    )
    assert by_department.json()["total"] == 2

    by_code = await client.get("/employees?q=A-0001", headers=headers)
    assert by_code.json()["total"] == 1


