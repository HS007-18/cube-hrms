async def test_employee_codes_are_immutable(client, auth, world):
    headers = await auth("hr_a")
    response = await client.patch(
        f"/employees/{world['employees']['emp_a']}",
        json={"employee_code": "HACK-1", "phone": "+91 98765 43210"},
        headers=headers,
    )
    assert response.status_code == 200
    assert response.json()["employee_code"] == "A-0003"
    assert response.json()["phone"] == "+91 98765 43210"
